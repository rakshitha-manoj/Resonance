#pragma once
/* On-node int8 autoencoder (anomaly score), Arduino-free, no heap, C and C++11.
   Pipeline per window:  base20 (ae_input.h)  ->  ae_make_input  ->  per-node normaliser (median / MAD of the 20
   commissioning windows)  ->  int8 quantisation  ->  int8 FullyConnected layers  ->  dequantise  ->  score = mean squared
   error in normalised space  ->  ratio = score / median commissioning score.
   The integer arithmetic reproduces TFLite's reference kernels bit for bit (reference_integer_ops::FullyConnected:
   int32 accumulation, MultiplyByQuantizedMultiplier with a single rounding, activation clamp), and the input quantisation is TFLite's reference QUANTIZE (round half away from zero of the float32 division val / scale, + zero
   point, clamp; verified against a real TFLite QUANTIZE op by tools/gen_ae_vectors.py). Weights and quantisation parameters: ae_model.h, GENERATED by tools/gen_ae.py. */
#include <stdint.h>
#include <math.h>
#include "ae_input.h"
#include "ae_model.h"

#define AE_COMM_N 20
#define AE_REF_MIN 1e-6f

/* ------------------------------------------------------------------ model input design (see models/tinyml/ae_report.md)
   Design A: the 20 base features as they are (16 az log band-powers, az_std, az_kurt, gx_std, gx_kurt). The shape-only
   alternatives (band means removed, log std) did worse on the validation split. */
typedef char ae_chk_n_in[(AE_N_IN == AE_NBASE) ? 1 : -1];
static inline void ae_make_input(const float *b, float *x) {
    for (int i = 0; i < AE_NBASE; i++) x[i] = b[i];
}

/* ------------------------------------------------------------------ TFLite integer helper
   MultiplyByQuantizedMultiplier as in the TFLite build that produced ae_int8.tflite (TensorFlow 2.21 Python wheel): ONE rounding,
   (x * multiplier + 2^(total_shift-1)) >> total_shift with total_shift = 31 - shift (the TFLITE_SINGLE_ROUNDING form).
   The older gemmlowp form (SaturatingRoundingDoublingHighMul then RoundingDivideByPOT, two roundings) differs in 28% of the
   vectors, so the choice is verified by test_ae against the interpreter, not assumed. */
static inline int32_t ae_mul_quant(int32_t x, int32_t mult, int shift) {
    int total = 31 - shift;
    int64_t r = (int64_t)x * (int64_t)mult + ((int64_t)1 << (total - 1));
    return (int32_t)(r >> total);
}

/* TFLite (2.21) reference QUANTIZE of one value: round_half_away_from_zero(val / scale) in float32 (a true division, NOT
   val * (1/scale): the two differ at near-half points), + zero point, clamp to int8.
   Out-of-range inputs: NaN -> -128; +-inf and huge values saturate to 127 / -128. TFLite's reference kernel converts the float
   to int32 with undefined behaviour there (x86 gives 127 for these), so for NaN the C result (-128) is a deliberate choice, not
   parity. Inputs from int16 sensor data (finite, normalised by the commissioning scale) never reach this range. */
static inline int8_t ae_quant_in(float v) {
    float t = roundf(v / AE_IN_SCALE);
    if (!(t == t)) return -128;
    if (t > 1000.0f) t = 1000.0f;
    if (t < -1000.0f) t = -1000.0f;
    int32_t q = (int32_t)t + AE_IN_ZP;
    return (int8_t)(q > 127 ? 127 : (q < -128 ? -128 : q));
}

/* in: AE_N_IN int8 -> out: AE_N_IN int8 */
static inline void ae_run_int8(const int8_t *in, int8_t *out) {
    int8_t a[AE_MAX_DIM], b[AE_MAX_DIM];
    const int8_t *src = in;
    int8_t *dst = a;
    for (int l = 0; l < AE_N_LAYERS; l++) {
        const AeLayer *L = &AE_LAYERS[l];
        for (int o = 0; o < L->n_out; o++) {
            int32_t acc = 0;
            const int8_t *w = L->w + o * L->n_in;
            for (int i = 0; i < L->n_in; i++) acc += (int32_t)w[i] * ((int32_t)src[i] + L->in_off);
            acc += L->bias[o];
            acc = ae_mul_quant(acc, L->mult[o], L->shift[o]);
            acc += L->out_off;
            if (acc < L->act_min) acc = L->act_min;
            if (acc > L->act_max) acc = L->act_max;
            dst[o] = (int8_t)acc;
        }
        src = dst;
        dst = (dst == a) ? b : a;
    }
    for (int i = 0; i < AE_N_IN; i++) out[i] = src[i];
}

static inline float ae_deq(int8_t q) { return (float)((int32_t)q - AE_OUT_ZP) * AE_OUT_SCALE; }

/* score = mean squared error between the normalised input z and the dequantised reconstruction */
static inline float ae_score_z(const float *z) {
    int8_t q[AE_N_IN], y[AE_N_IN];
    for (int i = 0; i < AE_N_IN; i++) q[i] = ae_quant_in(z[i]);
    ae_run_int8(q, y);
    float s = 0.0f;
    for (int i = 0; i < AE_N_IN; i++) {
        float d = z[i] - ae_deq(y[i]);
        s += d * d;
    }
    return s / (float)AE_N_IN;
}

/* ------------------------------------------------------------------ per-node commissioning normaliser */
typedef struct {
    int n;                              /* commissioning windows collected so far, 0..AE_COMM_N */
    float x[AE_COMM_N][AE_N_IN];        /* their model inputs, kept until the normaliser is formed */
    float med[AE_N_IN], scale[AE_N_IN]; /* valid when n == AE_COMM_N */
    float ref;                          /* median commissioning score */
} AeNode;

static inline void ae_node_reset(AeNode *nd) { nd->n = 0; nd->ref = 0.0f; }

/* median of 20 values: mean of the two middle ones (insertion sort on a copy) */
static inline float ae_median20(const float *v) {
    float s[AE_COMM_N];
    for (int i = 0; i < AE_COMM_N; i++) {
        float x = v[i];
        int j = i;
        while (j > 0 && s[j - 1] > x) { s[j] = s[j - 1]; j--; }
        s[j] = x;
    }
    return (s[AE_COMM_N / 2 - 1] + s[AE_COMM_N / 2]) * 0.5f;
}

static inline void ae_normalise(const AeNode *nd, const float *x, float *z) {
    for (int i = 0; i < AE_N_IN; i++) z[i] = (x[i] - nd->med[i]) / nd->scale[i];
}

/* Feed one commissioning window (base20). Returns 1 when this was the 20th and the normaliser + reference score are ready. */
static inline int ae_node_commission(AeNode *nd, const float *base20) {
    if (nd->n >= AE_COMM_N) return 0;
    ae_make_input(base20, nd->x[nd->n]);
    nd->n++;
    if (nd->n < AE_COMM_N) return 0;
    for (int i = 0; i < AE_N_IN; i++) {
        float col[AE_COMM_N], dev[AE_COMM_N];
        for (int w = 0; w < AE_COMM_N; w++) col[w] = nd->x[w][i];
        float med = ae_median20(col);
        for (int w = 0; w < AE_COMM_N; w++) dev[w] = fabsf(col[w] - med);
        float s = 1.4826f * ae_median20(dev);
        nd->med[i] = med;
        nd->scale[i] = s > AE_NORM_FLOOR[i] ? s : AE_NORM_FLOOR[i];
    }
    float sc[AE_COMM_N];
    for (int w = 0; w < AE_COMM_N; w++) {
        float z[AE_N_IN];
        ae_normalise(nd, nd->x[w], z);
        sc[w] = ae_score_z(z);
    }
    nd->ref = ae_median20(sc);
    if (!(nd->ref > AE_REF_MIN)) nd->ref = AE_REF_MIN;
    return 1;
}

/* 1 once the 20 commissioning windows are in and the normaliser / reference score exist. */
static inline int ae_node_ready(const AeNode *nd) { return nd->n >= AE_COMM_N; }

/* After commissioning: anomaly score ratio of one window (base20). *score_out (optional) = the raw score.
   Before commissioning completes (normaliser not formed) it returns 0.0 and sets *score_out to 0.0 (check ae_node_ready). */
static inline float ae_node_ratio(const AeNode *nd, const float *base20, float *score_out) {
    if (!ae_node_ready(nd)) {
        if (score_out) *score_out = 0.0f;
        return 0.0f;
    }
    float x[AE_N_IN], z[AE_N_IN];
    ae_make_input(base20, x);
    ae_normalise(nd, x, z);
    float s = ae_score_z(z);
    if (score_out) *score_out = s;
    return s / nd->ref;
}
