// Channel scan: the master's ESP-NOW channel follows its Wi-Fi router, so a slave that is not synced (power-on or LOST)
// cycles the channels 1..13, SCAN_DWELL_US (1.5 s, longer than the 1.4 s beacon period) each, starting on ESPNOW_CHANNEL,
// and stays on the channel where it first accepts a valid master beacon (host::ChannelScan, unit tested).
static host::ChannelScan g_scan(ESPNOW_CHANNEL);
static bool g_scan_was_on = false;
static void channel_scan_service() {
    bool hop = g_scan.update(now_us(), g_slave.synced());
    if (g_scan.scanning() && !g_scan_was_on) Serial.printf("scan: not synced, listening on channel %u, then cycling 1..13 (%u ms each)\r\n",
                                                           (unsigned)g_scan.channel(), (unsigned)(host::SCAN_DWELL_US / 1000));
    if (!g_scan.scanning() && g_scan_was_on) Serial.printf("scan: locked on channel %u\r\n", (unsigned)g_scan.channel());
    g_scan_was_on = g_scan.scanning();
    if (hop) {
        esp_wifi_set_channel(g_scan.channel(), WIFI_SECOND_CHAN_NONE);  // the broadcast peer uses channel 0 = current
    }
}
