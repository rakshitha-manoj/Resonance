"""Converts the netsim demo window traces into a C header for the Wokwi cloud demo (env master_wokwi_cloud).

    python tools/gen_demo_header.py [--bin test/data/demo_traces.bin] [--out include/demo_traces.h] [--decimate N]

Input: test/data/demo_traces.bin (layout in include/netsim.h: "RTRC" | u32 version=1 | u32 n_slaves=2 | u32 n_windows |
for slave 1, then slave 2: n_windows x (128 int16 az, 128 int16 gx), little endian) and its sidecar .floors ("5,10").
Output: include/demo_traces.h (GENERATED, gitignored; PlatformIO regenerates it before building the demo env, see
tools/pio_gen_demo.py):
    DEMO_N_WINDOWS, DEMO_FLOOR_1/2, static const int16_t DEMO_TRACE[2][DEMO_N_WINDOWS][256]  (az 0..127, gx 128..255)
The array lives in flash (const, 2 x 116 x 256 x 2 B = 118,784 B for the bundled trace). Every window is kept: no
decimation or shortening is needed (--decimate N keeps every N-th window only if a bigger trace does not fit).
Only the standard library is used (it runs inside PlatformIO's own Python).
"""
import argparse
import array
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)  # firmware/esp32


def read_trace(path):
    with open(path, "rb") as f:
        raw = f.read()
    magic, version, n_slaves, n_win = struct.unpack_from("<4sIII", raw, 0)
    if magic != b"RTRC" or version != 1 or n_slaves != 2 or n_win == 0:
        raise SystemExit("bad trace header in %s" % path)
    want = n_slaves * n_win * 256
    body = array.array("h")
    body.frombytes(raw[16:16 + want * 2])
    if sys.byteorder == "big":
        body.byteswap()
    if len(body) != want:
        raise SystemExit("truncated trace file %s" % path)
    return n_win, body


def read_floors(path):
    try:
        with open(path + ".floors") as f:
            a, b = f.read().strip().split(",")
            return int(a), int(b)
    except (OSError, ValueError):
        return 1, 2


def render(n_win, body, floors, decimate=1):
    keep = list(range(0, n_win, decimate))
    out = []
    out.append("#pragma once\n")
    out.append("// GENERATED by tools/gen_demo_header.py from test/data/demo_traces.bin. Do not edit, do not commit.\n")
    out.append("#include <stdint.h>\n")
    out.append("#define DEMO_N_WINDOWS %d\n" % len(keep))
    out.append("#define DEMO_FLOOR_1 %d\n#define DEMO_FLOOR_2 %d\n" % floors)
    out.append("// [slave 1..2][window = superframe][az 0..127, gx 128..255]\n")
    out.append("static const int16_t DEMO_TRACE[2][DEMO_N_WINDOWS][256] = {\n")
    for s in range(2):
        out.append("{\n")
        for w in keep:
            base = (s * n_win + w) * 256
            out.append("{" + ",".join(str(v) for v in body[base:base + 256]) + "},\n")
        out.append("},\n")
    out.append("};\n")
    return "".join(out), len(keep)


def generate(bin_path, out_path, decimate=1, quiet=False):
    """Writes out_path unless it is already newer than bin_path and this script. Returns True if (re)written."""
    if os.path.exists(out_path) and os.path.getmtime(out_path) >= max(os.path.getmtime(bin_path), os.path.getmtime(__file__)):
        return False
    n_win, body = read_trace(bin_path)
    text, kept = render(n_win, body, read_floors(bin_path), decimate)
    tmp = out_path + ".tmp"
    with open(tmp, "w", newline="\n") as f:
        f.write(text)
    os.replace(tmp, out_path)
    if not quiet:
        print("gen_demo_header: %s: %d of %d windows, %d bytes of int16 data" % (out_path, kept, n_win, 2 * kept * 256 * 2))
    return True


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--bin", default=os.path.join(ROOT, "test", "data", "demo_traces.bin"))
    ap.add_argument("--out", default=os.path.join(ROOT, "include", "demo_traces.h"))
    ap.add_argument("--decimate", type=int, default=1)
    a = ap.parse_args()
    if a.decimate < 1:
        raise SystemExit("--decimate must be >= 1")
    if os.path.exists(a.out):
        os.remove(a.out)  # explicit run: always rewrite
    generate(a.bin, a.out, a.decimate)


if __name__ == "__main__":
    main()
