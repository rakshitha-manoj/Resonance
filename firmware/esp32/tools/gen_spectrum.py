"""Writes include/spectrum_tables.h: Hann window (128) and Goertzel coefficients 2cos(2 pi f_j / FS) for the zoom
spectrum, as hex floats (float32 of a float64 computation) so host and ESP32 use identical values.
Run: .venv/Scripts/python.exe firmware/esp32/tools/gen_spectrum.py   (parameters must match spectrum.h)"""
from pathlib import Path
import numpy as np

FS, N, F0, DF, NZ = 100.0, 128, 3.0, 0.05, 181
root = Path(__file__).resolve().parents[3]


def hexf(v):
    return float.hex(float(np.float32(v))) + "f"


def table(name, a):
    rows = ["    " + ", ".join(hexf(v) for v in a[i:i + 4]) + "," for i in range(0, len(a), 4)]
    return f"static const float {name}[{len(a)}] = {{\n" + "\n".join(rows) + "\n};"


n = np.arange(N)
hann = 0.5 - 0.5 * np.cos(2 * np.pi * n / (N - 1))
f = F0 + np.arange(NZ) * DF
coeff = 2 * np.cos(2 * np.pi * f / FS)
params = [f"#define SPEC_TABLE_WIN_N {N}", f"#define SPEC_TABLE_ZOOM_N {NZ}",
          f"#define SPEC_TABLE_F0_MHZ {round(F0 * 1000)}  /* zoom start, millihertz */",
          f"#define SPEC_TABLE_DF_MHZ {round(DF * 1000)}  /* zoom step, millihertz */",
          f"#define SPEC_TABLE_FS_HZ {round(FS)}"]
lines = ["#pragma once", "/* GENERATED by tools/gen_spectrum.py */", *params, table("spec_hann", hann), table("spec_zoom_coeff", coeff), ""]
out = root / "firmware/esp32/include/spectrum_tables.h"
out.write_text("\n".join(lines))
print("wrote", out)
